import { useCallback } from "react";

import { loadAdminData } from "./adminData-loaders";

import type { AdminDataLoadProps } from "./adminData-loaders";

export function useAdminData(props: AdminDataLoadProps) {
  const {
    tab,
    api,
    loadStudents,
    catalogKind,
    auditAction,
    auditStart,
    auditEnd,
    role,
    timelineStudentId,
    setStats,
    setPending,
    setSessionOptions,
    setTypeOptions,
    setClassOptions,
    setCerts,
    setCatalog,
    setLogs,
    setRights,
    setBreaches,
    setReports,
    setTimeline,
    setReportsLoaded,
    setRightsLoaded,
    setBreachesLoaded,
    setContactEnquiries,
    setFaqs,
    setAdmins,
    setAnnouncement,
  } = props;
  return useCallback(() => loadAdminData({
    tab,
    api,
    loadStudents,
    catalogKind,
    auditAction,
    auditStart,
    auditEnd,
    role,
    timelineStudentId,
    setStats,
    setPending,
    setSessionOptions,
    setTypeOptions,
    setClassOptions,
    setCerts,
    setCatalog,
    setLogs,
    setRights,
    setBreaches,
    setReports,
    setTimeline,
    setReportsLoaded,
    setRightsLoaded,
    setBreachesLoaded,
    setContactEnquiries,
    setFaqs,
    setAdmins,
    setAnnouncement,
  }), [
    tab,
    api,
    loadStudents,
    catalogKind,
    auditAction,
    auditStart,
    auditEnd,
    role,
    timelineStudentId,
    setStats,
    setPending,
    setSessionOptions,
    setTypeOptions,
    setClassOptions,
    setCerts,
    setCatalog,
    setLogs,
    setRights,
    setBreaches,
    setReports,
    setTimeline,
    setReportsLoaded,
    setRightsLoaded,
    setBreachesLoaded,
    setContactEnquiries,
    setFaqs,
    setAdmins,
    setAnnouncement,
  ]);
}
